import assert from 'node:assert/strict';
import { readItemOptions, tradeItemKey, itemSnapshot } from './item-options.js';
import { combineLots, openGroups } from './trade-merge.js';
assert.deepEqual(readItemOptions({attack:'0',dex:'-1',remaining_upgrades:'7'}).value,{attack:0,dex:-1,remaining_upgrades:7});
for(const value of ['1.5','NaN','Infinity','2147483648']) assert.ok(readItemOptions({attack:value}).error);
assert.ok(readItemOptions({remaining_upgrades:-1}).error);
const base={name:'아대',buy_price:100,buy_qty:1,sell_price:null,sell_qty:0,item_id:'a',item_snapshot:{name:'아대',base_options:{attack:30}},item_options:{attack:35,dex:2}};
const reordered={...base,item_options:{dex:2,attack:35}};
assert.equal(tradeItemKey(base),tradeItemKey(reordered));
const other={...base,item_options:{attack:36,dex:2}};
assert.notEqual(tradeItemKey(base),tradeItemKey(other));
assert.deepEqual(openGroups([base,other]),[]);
assert.throws(()=>combineLots([base,other]),/옵션/);
assert.equal(combineLots([base,reordered]).buy_qty,2);
assert.deepEqual(combineLots([base,reordered]).item_options,base.item_options);
assert.notEqual(tradeItemKey({...base,item_id:'b'}),tradeItemKey(base));
const noOption={name:'legacy',buy_price:100,buy_qty:1,sell_price:null,sell_qty:0};
assert.equal(openGroups([noOption,{...noOption,buy_price:200}]).length,1);
assert.equal(combineLots([noOption,{...noOption,buy_price:200}]).buy_price,150);
